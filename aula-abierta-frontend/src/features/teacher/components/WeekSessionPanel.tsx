import { useEffect, useState } from 'react'
import { useMutation, useQueryClient } from '@tanstack/react-query'
import { CalendarClock, CalendarPlus, ExternalLink, Radio, Sparkles, Video } from 'lucide-react'
import { Button, Input, toast } from '@core/ui'
import { teacherApi } from '../api'
import type { Week } from '@core/types/models'

interface WeekSessionPanelProps {
  classroomId: number
  week: Week
}

// Only Google Meet links are valid — Jitsi and any other provider are rejected.
const GOOGLE_MEET_PREFIX = 'https://meet.google.com/'
const isGoogleMeetLink = (value: string) => value.trim().startsWith(GOOGLE_MEET_PREFIX)

export function WeekSessionPanel({ classroomId, week }: WeekSessionPanelProps) {
  const queryClient = useQueryClient()
  const [scheduledAt, setScheduledAt] = useState(week.session.session_scheduled_at?.slice(0, 16) ?? '')
  const [manualLink, setManualLink] = useState(week.session.meet_link ?? '')

  // Reflect server-side changes back into the input — e.g. the Google Meet link
  // generated by "Create with Calendar" after the weeks query refetches.
  const savedLink = week.session.meet_link ?? ''
  useEffect(() => {
    setManualLink(savedLink)
  }, [savedLink])

  const linkInvalid = manualLink.trim().length > 0 && !isGoogleMeetLink(manualLink)
  const savedLinkValid = Boolean(week.session.meet_link && isGoogleMeetLink(week.session.meet_link))

  const update = useMutation({
    mutationFn: (payload: { session_scheduled_at?: string | null; session_is_live?: boolean; create_google_meet?: boolean; meet_link?: string | null }) => teacherApi.updateWeekSession(classroomId, week.id, payload),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['trainer', 'classroom', classroomId, 'weeks'] })
      toast.success('Google Meet class updated.')
    },
    onError: () => toast.error('The Google Meet class could not be updated. Check the calendar connection.'),
  })

  const save = (createGoogleMeet = false) => {
    if (linkInvalid) {
      toast.error('Paste a Google Meet link (https://meet.google.com/...).')
      return
    }
    update.mutate({
      session_scheduled_at: scheduledAt || null,
      session_is_live: week.session.session_is_live,
      create_google_meet: createGoogleMeet,
      meet_link: manualLink.trim() || null,
    })
  }

  // Opens Google's instant-meeting creator in a new tab; the trainer copies the
  // generated meet.google.com link back into the field. Never uses Jitsi.
  const startInstantMeet = () => window.open('https://meet.google.com/new', '_blank', 'noopener,noreferrer')

  return (
    <section className="overflow-hidden rounded-2xl border border-neutral-200 bg-white shadow-sm dark:border-white/10 dark:bg-surface-card" aria-labelledby="live-class-title">
      <div className="flex items-start gap-3 border-b border-neutral-100 bg-brand-cream px-5 py-4 dark:border-white/10 dark:bg-white/[.04]">
        <span className="flex size-10 items-center justify-center rounded-xl bg-gradient-red text-white shadow-glow-red"><Video size={18} aria-hidden="true" /></span>
        <div><p className="text-xs font-extrabold text-brand-red">GOOGLE MEET</p><h2 id="live-class-title" className="mt-0.5 font-display text-xl font-extrabold text-neutral-900 dark:text-white">Live class control</h2></div>
      </div>
      <div className="space-y-4 p-5">
        <Input label="Schedule date and time" type="datetime-local" value={scheduledAt} onChange={(event) => setScheduledAt(event.target.value)} leftIcon={<CalendarClock size={17} />} fullWidth />

        <div>
          <Input
            label="Google Meet link"
            type="url"
            value={manualLink}
            onChange={(event) => setManualLink(event.target.value)}
            placeholder="https://meet.google.com/abc-defg-hij"
            fullWidth
          />
          <div className="mt-2 flex flex-wrap items-center justify-between gap-2">
            {linkInvalid ? (
              <p className="text-xs font-bold text-brand-red">Only Google Meet links are allowed.</p>
            ) : (
              <p className="text-xs font-semibold text-neutral-400 dark:text-neutral-500">Paste an existing meeting, or start a new one.</p>
            )}
            <button
              type="button"
              onClick={startInstantMeet}
              className="inline-flex items-center gap-1.5 rounded-lg px-2 py-1 text-xs font-bold text-brand-blue transition-colors duration-150 hover:bg-brand-sky/20"
            >
              <Sparkles size={13} aria-hidden="true" /> Start a Google Meet
            </button>
          </div>
        </div>

        <div className="flex items-center justify-between gap-4 rounded-xl border border-neutral-200 p-4 dark:border-white/10">
          <div><p className="text-sm font-bold text-neutral-900 dark:text-white">Class is live</p><p className="mt-1 text-xs font-semibold text-neutral-500 dark:text-neutral-400">Students see the join action immediately.</p></div>
          <button type="button" role="switch" aria-label="Class is live" aria-checked={week.session.session_is_live} onClick={() => update.mutate({ session_is_live: !week.session.session_is_live })} disabled={update.isPending} className={`relative h-7 w-12 shrink-0 overflow-hidden rounded-full transition-colors duration-200 ${week.session.session_is_live ? 'bg-brand-red' : 'bg-neutral-300 dark:bg-neutral-600'}`}><span className={`absolute top-1 left-1 size-5 rounded-full bg-white shadow-sm transition-transform duration-200 ${week.session.session_is_live ? 'translate-x-5' : 'translate-x-0'}`} /></button>
        </div>

        <div className="grid gap-3 sm:grid-cols-2">
          <Button variant="secondary" onClick={() => save(true)} loading={update.isPending} disabled={!scheduledAt} leftIcon={<CalendarPlus size={16} aria-hidden="true" />}>Create with Calendar</Button>
          <Button onClick={() => save(false)} loading={update.isPending} disabled={linkInvalid}>Save class</Button>
        </div>

        {savedLinkValid && (
          <a href={week.session.meet_link!} target="_blank" rel="noreferrer" className="flex min-h-11 items-center justify-center gap-2 rounded-xl bg-gradient-blue px-4 text-sm font-bold text-white no-underline shadow-glow-blue transition hover:brightness-105 hover:no-underline">
            <Radio size={16} aria-hidden="true" /> Open Google Meet <ExternalLink size={15} aria-hidden="true" />
          </a>
        )}
      </div>
    </section>
  )
}
